// Reads a DOCX the way the merge needs it (records 0025, 0028 and 0029): paragraphs in order
// (body and table cells), the SciDesk bookmarks that start in each, and its content as
// segments that are unchanged, inserted or deleted (with w:author and w:date). A citation
// field becomes one atom segment (U+FFFC) carrying its citationID, so that it counts 1, as
// a citation node does in ProseMirror. The paragraphs of the Zotero bibliography field are
// left out: the bibliography is generated, never imported. XML is parsed without DTDs or
// external entities (PLAN 6.6).
import { DOMParser, type Element, type Node } from "@xmldom/xmldom";
import JSZip from "jszip";
import { parseBookmark } from "@scidesk/formats";

const W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main";
const NEWLINE = String.fromCharCode(10);
export const ATOM ="\ufffc";

export interface Segment {
  text: string;
  kind: "same" | "ins" | "del";
  author: string | null;
  date: string | null;
  /** citationID of a citation atom. */
  citation?: string;
  /** Record 0096: where a comment's range starts or ends, or its reference is (an empty segment). */
  edge?: { comment: string; side: "start" | "end" | "ref" };
}
/** Record 0096: a comment of the copy (comments.xml), threaded by commentsExtended.xml. */
export interface DocxComment {
  /** Its w:id, which the ranges in the text point to. */
  word: string;
  author: string;
  date: string | null;
  text: string;
  /** The w:id of the comment it answers; null for a comment that starts a thread. */
  parent: string | null;
  /** Resolved (w15:done). */
  done: boolean;
  /** w16cid:durableId, which Word keeps when it saves. */
  durableId: string | null;
}
export interface DocxParagraph {
  index: number;
  /** Ids of the SciDesk block bookmarks that start in this paragraph (in order). */
  blocks: string[];
  segments: Segment[];
  /** The paragraph mark was inserted or deleted with tracked changes. */
  mark: { kind: "ins" | "del"; author: string; date: string | null } | null;
  inTable: boolean;
  /** Text before the block's bookmark: generated by the export ("Tabla 1. ", a note's letter), not content. */
  lead: string;
}
export interface DocxRead {
  paragraphs: DocxParagraph[];
  /** The custom property "SciDesk", parsed, if it is there. */
  scidesk: Record<string, unknown> | null;
  /** The snapshot bookmark (_SDs_), the fallback when properties were lost. */
  snapshotBookmark: string | null;
  lastModifiedBy: string;
  /** Record 0096: the comments, in the order of comments.xml. */
  comments: DocxComment[];
}

const kids = (n: Node): Element[] => {
  const o: Element[] = [];
  for (let c = n.firstChild; c; c = c.nextSibling) if (c.nodeType === 1) o.push(c as Element);
  return o;
};
const attr = (e: Element, a: string) => e.getAttributeNS(W, a) || e.getAttribute(`w:${a}`) || "";
const MAX_XML = 50 * 1024 * 1024;

function parseXml(xml: string) {
  if (xml.length > MAX_XML) throw new Error("document.xml is too large");
  if (/<!DOCTYPE/i.test(xml)) throw new Error("DOCX with a DTD refused");
  return new DOMParser().parseFromString(xml, "text/xml");
}

export async function readDocx(bytes: Uint8Array): Promise<DocxRead> {
  const zip = await JSZip.loadAsync(bytes);
  const docXml = await zip.file("word/document.xml")?.async("string");
  if (!docXml) throw new Error("not a Word document (no word/document.xml)");
  const dom = parseXml(docXml);
  const custom = await zip.file("docProps/custom.xml")?.async("string");
  let scidesk: Record<string, unknown> | null = null;
  if (custom) {
    const m = /<property [^>]*name="SciDesk"[^>]*>\s*<vt:lpwstr>([^<]*)<\/vt:lpwstr>/.exec(custom);
    if (m) try { scidesk = JSON.parse(m[1].replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&")); } catch { scidesk = null; }
  }
  const core = await zip.file("docProps/core.xml")?.async("string");
  const lastModifiedBy = /<cp:lastModifiedBy>([^<]*)</.exec(core ?? "")?.[1] ?? "";

  const paragraphs: DocxParagraph[] = [];
  let snapshotBookmark: string | null = null;
  let inBibliography = false;
  let inTable = 0;

  function paragraph(p: Element) {
    const P: DocxParagraph = { index: paragraphs.length, blocks: [], segments: [], mark: null, inTable: inTable > 0, lead: "" };
    // until the bookmark of the text block (b- or n-) starts, text is the generated lead
    let inLead = true;
    let sawBlock = false;
    // record 0070: where a table or figure part starts in a paragraph without a text block
    // (the file name left in place of an image), the text before it is generated too
    let partLead: number | null = null;
    const leadSegments: Segment[] = [];
    const pPr = kids(p).find((e) => e.localName === "pPr");
    const markRPr = pPr && kids(pPr).find((e) => e.localName === "rPr");
    const markRev = markRPr && kids(markRPr).find((e) => e.localName === "ins" || e.localName === "del");
    if (markRev) P.mark = { kind: markRev.localName as "ins" | "del", author: attr(markRev, "author"), date: attr(markRev, "date") || null };

    // complex fields: begin → instruction → separate → result → end, possibly over many runs
    type Field = { instr: string; phase: "instr" | "result"; kind: "citation" | "ref" | "bibliography" | "other"; citation?: string; emitted: boolean };
    const stack: Field[] = [];
    const push = (text: string, kind: Segment["kind"], rev: { author: string; date: string } | null, citation?: string) => {
      if (!text) return;
      const into = inLead ? leadSegments : P.segments;
      const last = into.at(-1);
      if (!citation && last && !last.citation && !last.edge && last.kind === kind && last.author === (rev?.author ?? null) && last.date === (rev?.date || null)) last.text += text;
      else into.push({ text, kind, author: rev?.author ?? null, date: rev?.date || null, ...(citation ? { citation } : {}) });
    };
    const run = (r: Element, kind: Segment["kind"], rev: { author: string; date: string } | null) => {
      for (const e of kids(r)) {
        const ln = e.localName;
        if (ln === "fldChar") {
          const t = attr(e, "fldCharType");
          if (t === "begin") stack.push({ instr: "", phase: "instr", kind: "other", emitted: false });
          else if (t === "separate" && stack.length) {
            const f = stack.at(-1)!;
            f.phase = "result";
            const instr = f.instr.trim();
            if (/^ADDIN ZOTERO_ITEM CSL_CITATION|^ADDIN CSL_CITATION/.test(instr)) {
              f.kind = "citation";
              try { f.citation = String(JSON.parse(instr.slice(instr.indexOf("{"))).citationID); } catch { f.citation = "?"; }
            } else if (/^ADDIN ZOTERO_BIBL/.test(instr)) { f.kind = "bibliography"; inBibliography = true; }
            else if (/^REF _SDn_/.test(instr)) f.kind = "ref"; // a cross-reference or a note call: one atom
          } else if (t === "end" && stack.length) {
            const f = stack.pop()!;
            if (f.kind === "bibliography") inBibliography = false;
          }
          continue;
        }
        const f = stack.at(-1);
        if (ln === "instrText" || ln === "delInstrText") { if (f && f.phase === "instr") f.instr += e.textContent ?? ""; continue; }
        if ((f?.kind === "citation" || f?.kind === "ref") && f.phase === "result") {
          if (!f.emitted) { push(ATOM, kind, rev, f.citation); f.emitted = true; }
          continue; // the formatted result is citeproc-js', not the co-author's text
        }
        if (f && f.phase === "instr") continue;
        if (ln === "t" || ln === "delText") push(e.textContent ?? "", kind, rev);
        else if (ln === "tab") push("\t", kind, rev);
        // record 0078: a page or column break is layout, not text (a page break block exports as one)
        else if (ln === "br") { if (!["page", "column"].includes(attr(e, "type"))) push("\n", kind, rev); }
        else if (ln === "commentReference") (inLead ? leadSegments : P.segments).push({ text: "", kind: "same", author: null, date: null, edge: { comment: attr(e, "id"), side: "ref" } });
        else if (ln === "noBreakHyphen") push("\u2011", kind, rev);
      }
    };
    const walk = (n: Element, kind: Segment["kind"], rev: { author: string; date: string } | null) => {
      for (const e of kids(n)) {
        const ln = e.localName;
        if (ln === "r") run(e, kind, rev);
        else if (ln === "ins" || ln === "moveTo") walk(e, "ins", { author: attr(e, "author"), date: attr(e, "date") });
        else if (ln === "del" || ln === "moveFrom") walk(e, "del", { author: attr(e, "author"), date: attr(e, "date") });
        else if (ln === "bookmarkStart") {
          const b = parseBookmark(attr(e, "name"));
          if (b?.marker === "block") {
            P.blocks.push(b.id);
            if (/^(b|n)-/.test(b.id)) { inLead = false; sawBlock = true; }
            else if (/^(t|f)-/.test(b.id) && !sawBlock && partLead === null) partLead = leadSegments.length;
          }
          if (b?.marker === "snapshot") snapshotBookmark = b.id;
        } else if (ln === "commentRangeStart" || ln === "commentRangeEnd") {
          (inLead ? leadSegments : P.segments).push({ text: "", kind: "same", author: null, date: null, edge: { comment: attr(e, "id"), side: ln === "commentRangeStart" ? "start" : "end" } });
        } else if (ln === "hyperlink" || ln === "smartTag" || ln === "sdt" || ln === "sdtContent" || ln === "fldSimple" || ln === "customXml") walk(e, kind, rev);
      }
    };
    const startsInBibliography = inBibliography;
    walk(p, "same", null);
    // a paragraph without SciDesk marks (new, or from another program): all of it is content
    if (!sawBlock && partLead !== null) {
      P.lead = leadSegments.slice(0, partLead).map((x) => x.text).join("");
      P.segments.unshift(...leadSegments.slice(partLead));
    } else if (!sawBlock) P.segments.unshift(...leadSegments);
    else {
      P.lead = leadSegments.map((x) => x.text).join("");
      // a comment that starts in the generated text starts where the content does
      P.segments.unshift(...leadSegments.filter((x) => x.edge));
    }
    if (startsInBibliography || (inBibliography && !P.blocks.length)) return; // generated text
    paragraphs.push(P);
  }
  function blocks(n: Element) {
    for (const e of kids(n)) {
      if (e.localName === "p") paragraph(e);
      else if (e.localName === "tbl") { inTable++; for (const tr of kids(e).filter((x) => x.localName === "tr")) for (const tc of kids(tr).filter((x) => x.localName === "tc")) blocks(tc); inTable--; }
      else if (e.localName === "sdt" || e.localName === "sdtContent" || e.localName === "customXml") blocks(e);
    }
  }
  const body = dom.getElementsByTagNameNS(W, "body")[0];
  if (!body) throw new Error("document.xml has no body");
  blocks(body as unknown as Element);
  // a paragraph with the snapshot bookmark only is not content
  const content = paragraphs.filter((p) => p.blocks.length || p.segments.some((s) => s.text.trim() || s.edge));
  return { paragraphs: content.map((p, i) => ({ ...p, index: i })), scidesk, snapshotBookmark, lastModifiedBy, comments: await readComments(zip) };
}

/** Record 0096: comments.xml, with the threads and the resolved state of commentsExtended.xml and the durable ids of commentsIds.xml. */
async function readComments(zip: JSZip): Promise<DocxComment[]> {
  const xml = await zip.file("word/comments.xml")?.async("string");
  if (!xml) return [];
  const all = (n: { getElementsByTagName(name: string): unknown }, name: string) => [...(n.getElementsByTagName(name) as Iterable<Element>)];
  // the last paragraph of each comment carries the w14:paraId the other two parts point to
  const ext = new Map<string, { parent: string | null; done: boolean }>();
  const extXml = await zip.file("word/commentsExtended.xml")?.async("string");
  if (extXml) for (const e of all(parseXml(extXml), "w15:commentEx")) ext.set(e.getAttribute("w15:paraId") ?? "", { parent: e.getAttribute("w15:paraIdParent") || null, done: e.getAttribute("w15:done") === "1" });
  const durable = new Map<string, string>();
  const idsXml = await zip.file("word/commentsIds.xml")?.async("string");
  if (idsXml) for (const e of all(parseXml(idsXml), "w16cid:commentId")) durable.set(e.getAttribute("w16cid:paraId") ?? "", e.getAttribute("w16cid:durableId") ?? "");
  const comments: (DocxComment & { paraId: string; parentPara: string | null })[] = [];
  for (const c of all(parseXml(xml), "w:comment")) {
    const paras = all(c, "w:p");
    const lines = paras.map((p) => all(p, "w:t").map((t) => t.textContent ?? "").join(""));
    const paraId = paras.at(-1)?.getAttribute("w14:paraId") ?? "";
    const x = ext.get(paraId);
    comments.push({ word: attr(c, "id"), author: attr(c, "author"), date: attr(c, "date") || null, text: lines.join(NEWLINE), parent: null, done: x?.done ?? false, durableId: durable.get(paraId) || null, paraId, parentPara: x?.parent ?? null });
  }
  const byPara = new Map(comments.filter((c) => c.paraId).map((c) => [c.paraId, c.word]));
  return comments.map(({ paraId: _, parentPara, ...c }) => ({ ...c, parent: parentPara ? (byPara.get(parentPara) ?? null) : null }));
}

/**
 * Record 0095: the tracked changes the Word for co-authors carried from the version sent
 * (recognised by author and date, which Word keeps; it renumbers w:id) are part of that
 * version, not the co-author's: an insertion is plain text and a deletion is not there, as in
 * the sent blocks, which have them accepted. The co-author's own changes stay as they are.
 */
export function settleSentChanges(read: DocxRead, sent: Set<string>, key: (author: string, date: string | null) => string): DocxRead {
  const isSent = (s: { author: string | null; date: string | null }) => s.author !== null && sent.has(key(s.author, s.date));
  const paragraphs = read.paragraphs.map((p) => {
    const segments: Segment[] = [];
    for (const s of p.segments) {
      if (s.kind !== "same" && isSent(s)) {
        if (s.kind === "ins") segments.push({ ...s, kind: "same", author: null, date: null });
        continue;
      }
      segments.push({ ...s });
    }
    // plain text next to plain text is one segment, as the reader gives it
    const joined: Segment[] = [];
    for (const s of segments) {
      const last = joined.at(-1);
      if (last && s.kind === "same" && last.kind === "same" && !s.citation && !last.citation && !s.edge && !last.edge) last.text += s.text;
      else joined.push(s);
    }
    const mark = p.mark && isSent(p.mark) ? null : p.mark;
    return { ...p, segments: joined, mark };
  });
  return { ...read, paragraphs };
}

/** Text of a paragraph with every tracked change rejected (as it was sent, plus untracked edits). */
export const rejectedText = (p: DocxParagraph) => p.segments.filter((s) => s.kind !== "ins").map((s) => s.text).join("");
/** Text with every tracked change accepted. */
export const acceptedText = (p: DocxParagraph) => p.segments.filter((s) => s.kind !== "del").map((s) => s.text).join("");
